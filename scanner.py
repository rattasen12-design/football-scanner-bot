@app.route('/upload_and_scan', methods=['POST'])
def upload_and_scan():
    files = request.files.getlist('screenshots')
    saved_files = []
    
    for file in files:
        if file and file.filename != '':
            filename = secure_filename(file.filename)
            filepath = os.path.join(app.config['UPLOAD_FOLDER'], filename)
            file.save(filepath)
            saved_files.append(filename)

    match_name = request.form.get('match_name', 'คู่แข่งขันจากภาพสแกน')
    league = request.form.get('league', 'รายการลีก')
    group_type = request.form.get('group_type', 'กลุ่มที่ 1: เกรด A+ (ทีเด็ดคัดเน้นๆ ความเสี่ยงต่ำสุด)')

    result = evaluate_formula_7_parts(match_name, league, group_type, len(saved_files))
    return jsonify(result)

